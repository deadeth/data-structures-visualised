// Record the narration of design tours with Piper. Usage, from the repo root:
//   node scripts/audio/render.mjs <design id> [<design id> ...] [--force] [--print]
// For the main tour and each story it writes public/audio/<design>/<main|story id>/<n>.mp3 (n from 1)
// and rewrites src/designs/narration-manifest.ts with the hash of the words each clip was made from.
// A clip whose words are unchanged is skipped unless --force. --print only prints what would be spoken.
// Locked designs are refused.
// Needs python3 with piper-tts, a Piper voice (env PIPER_VOICE) and ffmpeg. See README.md beside this file.
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runnerImport } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = process.argv.slice(2);
const force = args.includes('--force');
const print = args.includes('--print');
const ids = args.filter((a) => !a.startsWith('--'));
if (!ids.length) {
  console.error('Usage: node scripts/audio/render.mjs <design id> [...] [--force]');
  process.exit(1);
}
const voice = process.env.PIPER_VOICE ?? '/tmp/voices/en_GB-cori-high.onnx';
const python = process.env.PIPER_PYTHON ?? 'python3';
const ffmpeg = process.env.FFMPEG ?? 'ffmpeg';
if (!print && !existsSync(voice)) {
  console.error(`No Piper voice at ${voice}. Set PIPER_VOICE to the .onnx file (its .onnx.json must sit beside it).`);
  process.exit(1);
}

const load = async (file) => (await runnerImport(file, { configFile: false, logLevel: 'error', root })).module;
const { LOCKED_IDS } = await load(join(root, 'src/locked/manifest.ts'));
const locked = ids.filter((id) => LOCKED_IDS.includes(id));
if (locked.length) {
  console.error(
    `Refusing ${locked.join(', ')}: locked page${locked.length > 1 ? 's' : ''}. Their text ships only encrypted (src/locked/manifest.ts), ` +
      'and clips under public/audio are served to anyone, so recording them would publish the locked words.',
  );
  process.exit(1);
}
const { narrationOf, spoken, hashOf } = await load(join(root, 'src/designs/narration.ts'));
const { DESIGNS } = await load(join(root, 'src/designs/index.ts'));
const manifestFile = join(root, 'src/designs/narration-manifest.ts');
const { NARRATION } = existsSync(manifestFile) ? await load(manifestFile) : { NARRATION: {} };
const manifest = structuredClone(NARRATION ?? {});

function writeManifest() {
  const sorted = Object.fromEntries(Object.keys(manifest).sort().map((d) => [d, manifest[d]]));
  writeFileSync(
    manifestFile,
    '// Generated by scripts/audio/render.mjs: do not edit by hand.\n' +
      '// For each design and tour ("main" or a story id), the hash (hashOf in narration.ts) of the words each step\'s clip\n' +
      '// public/audio/<design>/<tour>/<n>.mp3 was recorded from. The page plays a clip only while its hash still matches.\n' +
      `export const NARRATION: Record<string, Record<string, string[]>> = ${JSON.stringify(sorted, null, 2)};\n`,
  );
}

const work = mkdtempSync(join(tmpdir(), 'narration-'));
const seconds = (f) => Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString().trim());

for (const id of ids) {
  const entry = DESIGNS.find((d) => d.id === id);
  if (!entry) {
    console.error(`No public design called "${id}". Known: ${DESIGNS.map((d) => d.id).join(', ')}.`);
    process.exit(1);
  }
  // The registry's load() is a dynamic import, which the closed module runner cannot follow: load the file instead.
  const mod = await load(join(root, 'src/designs', `${id}.ts`));
  const design = Object.values(mod).find((x) => x && typeof x === 'object' && x.id === id && Array.isArray(x.tour));
  if (!design) throw new Error(`src/designs/${id}.ts exports no design with id "${id}"`);
  const tours = [['main', design.tour], ...(design.stories ?? []).map((s) => [s.id, s.tour])];
  if (print) {
    for (const [key, tour] of tours) tour.forEach((st, i) => console.log(`=== ${id}/${key}/${i + 1}\n${spoken(narrationOf(st, i + 1))}\n`));
    continue;
  }
  manifest[id] ??= {};
  for (const [key, tour] of tours) {
    const dir = join(root, 'public/audio', id, key);
    mkdirSync(dir, { recursive: true });
    const had = manifest[id][key] ?? [];
    const hashes = [];
    let total = 0;
    let bytes = 0;
    for (let i = 0; i < tour.length; i++) {
      const n = i + 1;
      const text = narrationOf(tour[i], n);
      const hash = hashOf(text);
      const out = join(dir, `${n}.mp3`);
      if (!force && had[i] === hash && existsSync(out)) {
        hashes.push(hash);
      } else {
        const wav = join(work, `${n}.wav`);
        const say = spoken(text);
        const r = spawnSync(python, ['-m', 'piper', '-m', voice, '-f', wav, '--sentence-silence', '0.3'], { input: say, stdio: ['pipe', 'ignore', 'pipe'] });
        if (r.status !== 0) throw new Error(`piper failed on ${id}/${key}/${n}: ${r.stderr}`);
        execFileSync(ffmpeg, ['-y', '-v', 'error', '-i', wav, '-af', 'loudnorm=I=-16:TP=-1.5,apad=pad_dur=0.3', '-ac', '1', '-ar', '22050', '-c:a', 'libmp3lame', '-b:a', '40k', out]);
        rmSync(wav);
        hashes.push(hash);
        // Saved after every clip, so a stopped run keeps what it made.
        manifest[id][key] = [...hashes, ...had.slice(hashes.length).map(() => '')];
        writeManifest();
      }
      const d = seconds(out);
      const b = statSync(out).size;
      total += d;
      bytes += b;
      console.log(`${id}/${key}/${n}.mp3  ${d.toFixed(1)} s  ${(b / 1024).toFixed(0)} KB`);
    }
    manifest[id][key] = hashes;
    writeManifest();
    console.log(`${id}/${key}: ${tour.length} clips, ${(total / 60).toFixed(1)} min, ${(bytes / 1024 / 1024).toFixed(2)} MB`);
  }
  // Clips for steps or stories that no longer exist are left on disk; the manifest no longer names them.
  for (const key of Object.keys(manifest[id])) if (!tours.some(([k]) => k === key)) delete manifest[id][key];
  writeManifest();
}
rmSync(work, { recursive: true, force: true });
